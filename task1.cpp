#include <iostream>
int main(){
    std::cout<<"Int size =" <<sizeof(int) <<std::endl;
    std::cout<<"Long size =" <<sizeof(long)<<std::endl;
    std::cout<<"Double size =" <<sizeof(double)<<std::endl;
    std::cout<<"Float size =" <<sizeof(float)<<std::endl;
    std::cout<<"Char size =" <<sizeof(char)<<std::endl;
    return 0;
}